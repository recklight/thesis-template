_LOG = get_logger(__name__)

_MAX_REPORTED_MESSAGES = 25


class BuildTarget(str, Enum):
    """What to compile."""

    THESIS = "thesis"
    SPINE = "spine"


@dataclass(frozen=True, slots=True)
class BuildOutcome:
    """Low-level result of a compilation, before it becomes a report."""

    target: BuildTarget
    source: Path
    output: Path | None
    commands: tuple[CommandResult, ...]
    log: LogReport
    missing_fonts: tuple[str, ...] = ()


def render_generated_settings(config: ThesisConfig) -> str:
    r"""Render the LaTeX file that carries ``thesis.toml`` into the document.

    Parameters
    ----------
    config : ThesisConfig
        Project configuration.

    Returns
    -------
    str
        Contents of ``config/generated.tex``.

    Notes
    -----
    The table-of-contents style and the watermark mode are set in
    ``thesis.toml`` and this file is generated from them, so changing a
    style is one changed line in a diff instead of commenting LaTeX lines in
    and out.  A hand edit here is overwritten by the next build, hence the
    do-not-edit banner.

    Examples
    --------
    >>> from pathlib import Path
    >>> text = render_generated_settings(ThesisConfig.default(Path(".")))
    >>> "\\ThesisTocStyleCJKFull" in text
    True
    """
    template = config.template
    watermark_image = Path(template.watermark_image).as_posix()
    if Path(watermark_image).suffix:
        watermark_image = watermark_image[: -len(Path(watermark_image).suffix)]

    lines = [
        "% ---------------------------------------------------------------",
        "% Generated by thesis-cli from thesis.toml -- DO NOT EDIT BY HAND.",
        "% Change the [template] section of thesis.toml and rebuild.",
        "% ---------------------------------------------------------------",
        f"\\{template.toc_style.macro}",
        f"\\renewcommand{{\\thesisFloatSpec}}{{{template.float_spec}}}",
        f"\\renewcommand{{\\thesisWatermarkImage}}{{{watermark_image}}}",
        f"\\setlength{{\\thesisWatermarkWidth}}{{{template.watermark_width}}}",
        f"\\renewcommand{{\\thesisWatermarkX}}{{{template.watermark_x}}}",
        f"\\renewcommand{{\\thesisWatermarkY}}{{{template.watermark_y}}}",
        f"\\ThesisWatermark{{{template.watermark.value}}}",
        "",
    ]
    return "\n".join(lines)


def write_generated_settings(config: ThesisConfig) -> Path:
    """Write ``config/generated.tex`` when its contents would change.

    Parameters
    ----------
    config : ThesisConfig
        Project configuration.

    Returns
    -------
    pathlib.Path
        The file that was written or left untouched.

    Notes
    -----
    Rewriting an unchanged file would update its modification time and make
    ``latexmk`` recompile the whole thesis on every invocation, so the
    contents are compared first.
    """
    target = config.generated_path
    contents = render_generated_settings(config)
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.is_file():
        try:
            if target.read_text(encoding="utf-8") == contents:
                return target
        except OSError:  # pragma: no cover - unreadable file is rewritten
            pass
    target.write_text(contents, encoding="utf-8")
    _LOG.info("Wrote %s", target)
    return target


def validate_main_document(path: Path) -> None:
    r"""Reject a target that is not a compilable LaTeX document.

    Parameters
    ----------
    path : pathlib.Path
        File to build.

    Raises
    ------
    ProjectLayoutError
        The file does not exist.
    ValidationError
        The file is a ``.bib``, ``.cls``, ``.sty`` or ``.bst`` file, or a
        fragment with no ``\documentclass`` or no ``\begin{document}``.

    Notes
    -----
    The markers are looked for after comments are stripped, so a
    commented-out ``\documentclass`` does not make a fragment compilable.
    Pointing the engine at a ``.bib`` or at a chapter is an easy slip once a
    project has dozens of ``.tex`` files; the module docstring says what TeX
    makes of it.
    """
    if not path.is_file():
        raise ProjectLayoutError(
            f"Cannot build: {path} does not exist.",
            hint="Check the 'main' key in thesis.toml, or pass an explicit file.",
        )
    if path.suffix.lower() in {".bib", ".cls", ".sty", ".bst"}:
        raise ValidationError(
            f"{path.name} is a {path.suffix} file, not a LaTeX document.",
            hint="Build the main document instead; run 'thesis-cli build' with no arguments.",
        )

    raw = path.read_bytes().decode("utf-8", errors="replace")
    code = clean_source(raw).code
    has_class = "\\documentclass" in code
    has_body = "\\begin{document}" in code
    if has_class and has_body:
        return

    missing = []
    if not has_class:
        missing.append("\\documentclass")
    if not has_body:
        missing.append("\\begin{document}")
    raise ValidationError(
        f"{path.name} is a LaTeX fragment, not a compilable document "
        f"(no {' and no '.join(missing)}).",
        hint=(
            "Fragments are meant to be pulled in with \\input from the main document. "
            "Run 'thesis-cli build' to compile the document configured in thesis.toml."
        ),
    )


def _preflight(config: ThesisConfig, source: Path, target: BuildTarget) -> list[Finding]:
    """Check everything that can be checked without starting TeX."""
    findings: list[Finding] = []

    for path in config.bib_paths:
        if not path.is_file():
            findings.append(
                Finding(
                    severity=Severity.ERROR,
                    kind="missing-bib",
                    location=str(path),
                    message="Bibliography file listed in thesis.toml does not exist.",
                )
            )

    if config.template.watermark is not WatermarkMode.OFF:
        watermark = config.watermark_path
        if not watermark.is_file():
            stem_matches = [
                candidate
                for candidate in watermark.parent.glob(watermark.stem + ".*")
                if candidate.is_file()
            ]
            if not stem_matches:
                findings.append(
                    Finding(
                        severity=Severity.ERROR,
                        kind="missing-watermark",
                        location=str(watermark),
                        message=(
                            'Watermark image not found; set template.watermark = "off" in '
                            "thesis.toml or provide the file."
                        ),
                    )
                )

    if target is BuildTarget.THESIS:
        document: TexDocument = scan_document(
            source,
            config.root,
            macros=config.figure_macros,
            label_macros=config.label_macros,
        )
        index = DirectoryIndex()
        for reference in document.graphics:
            resolution = resolve_reference(
                reference,
                root=config.root,
                search_dirs=config.figure_dirs,
                extensions=tuple(config.figures.extensions),
                index=index,
            )
            if resolution.status in (FigureStatus.OK, FigureStatus.MACRO):
                continue
            severity = Severity.ERROR
            message = (
                f"Graphic '{reference.raw}' was not found."
                if resolution.status is FigureStatus.MISSING
                else (
                    f"Graphic '{reference.raw}' differs in case from "
                    f"'{resolution.actual_name}' on disk."
                )
            )
            findings.append(
                Finding(
                    severity=severity,
                    kind=f"figure-{resolution.status.value}",
                    location=reference.location.render(config.root),
                    message=message,
                )
            )
        for missing in document.missing_inputs:
            findings.append(
                Finding(
                    severity=Severity.ERROR,
                    kind="missing-input",
                    location=missing.location.render(config.root),
                    message=f"\\{missing.command}{{{missing.target}}} cannot be resolved.",
                )
            )
    return findings


def _needs_bibtex(target: BuildTarget, aux_file: Path) -> bool:
    r"""Decide after the first pass whether ``bibtex`` has anything to do.

    BibTeX exits with an error on an ``.aux`` that has no ``\bibdata``,
    which is the case for the spine and for any document without a
    bibliography, so it only runs when the first pass asked for one.  The
    child ``.aux`` files named by ``\@input`` are read too, as BibTeX reads
    them: with ``\bibliography`` in a file pulled in by ``\include``, the
    ``\bibdata`` line lands in that file's own ``.aux``.
    """
    if target is BuildTarget.SPINE:
        return False
    return bool(parse_aux(aux_file).bibdata)


def _succeeded(result: CommandResult) -> bool:
    """Return ``True`` unless *result* should fail the build.

    ``bibtex`` exits with 1 when it only printed warnings (an empty field,
    say); the bibliography is still written, so only 2 and above count.
    """
    if result.command and result.command[0] == BIBTEX_PROGRAM and not result.timed_out:
        return result.returncode in (0, 1)
    return result.ok


def _run_sequence(
    config: ThesisConfig,
    source: Path,
    output_dir: Path,
    *,
    use_latexmk: bool,
    target: BuildTarget = BuildTarget.THESIS,
) -> list[CommandResult]:
    """Run either ``latexmk`` or the explicit multi-pass sequence."""
    spec = engine_spec(config.build.engine)
    env = build_environment(config)
    results: list[CommandResult] = []

    if use_latexmk:
        require_executable(LATEXMK_PROGRAM, purpose="driving the multi-pass build")
        require_executable(spec.program, purpose=f"running the {config.build.engine.value} engine")
        command = latexmk_command(config, source, output_dir=output_dir)
        results.append(run_command(command, cwd=config.root, env=env))
        return results

    require_executable(spec.program, purpose=f"running the {config.build.engine.value} engine")
    commands = manual_sequence(config, source, output_dir=output_dir)
    bibtex_available = find_executable(BIBTEX_PROGRAM) is not None
    for command in commands:
        if command[0] == BIBTEX_PROGRAM:
            if not _needs_bibtex(target, output_dir / f"{source.stem}.aux"):
                _LOG.info("No \\bibdata in the first pass; skipping bibtex")
                continue
            if not bibtex_available:
                _LOG.warning("bibtex not found; skipping the bibliography pass")
                continue
            # bibtex resolves relative names from its own working directory,
            # so it runs inside the output directory where the .aux lives;
            # BIBINPUTS (set above) points it back at the sources.
            results.append(run_command(command, cwd=output_dir, env=env))
            continue
        result = run_command(command, cwd=config.root, env=env)
        results.append(result)
        if not result.ok and config.build.halt_on_error:
            break
    return results


def build_document(
    config: ThesisConfig,
    *,
    target: BuildTarget = BuildTarget.THESIS,
    use_latexmk: bool | None = None,
    preflight: bool = True,
) -> CommandReport:
    """Compile the thesis (or the spine sheet) and summarise the run.

    Parameters
    ----------
    config : ThesisConfig
        Project configuration.
    target : BuildTarget, optional
        ``THESIS`` for the main document, ``SPINE`` for the printed spine.
    use_latexmk : bool or None, optional
        Override ``build.use_latexmk``.
    preflight : bool, optional
        Run the pre-compilation checks.

    Returns
    -------
    CommandReport
        Findings from the preflight and from the TeX log, plus a table of
        the commands that ran.

    Raises
    ------
    ValidationError
        The target is not a compilable document.
    BuildFailedError
        A preflight check failed, or the engine exited non-zero.

    Notes
    -----
    The spine is a separate landscape document, and ``dvipdfmx`` needs ``-l``
    to place it correctly; ``target=SPINE`` adds that flag.
    """
    source = config.main_path if target is BuildTarget.THESIS else config.spine_path
    validate_main_document(source)

    # generated.tex is ignored by git in a thesis project, so a fresh clone does
    # not have it. Write it first, or preflight reports the \input as missing.
    write_generated_settings(config)

    findings: list[Finding] = []
    if preflight:
        findings.extend(_preflight(config, source, target))
        fatal = [item for item in findings if item.severity is Severity.ERROR]
        if fatal:
            report = CommandReport(
                command=f"build ({target.value})",
                findings=tuple(findings),
                summary={"source": str(source), "status": "preflight-failed"},
            )
            raise BuildFailedError(
                f"Preflight found {len(fatal)} problem(s); nothing was compiled.",
                hint="Run 'thesis-cli figures' and 'thesis-cli check-refs' for detail.",
                report=report,
            )

    output_dir = config.output_dir
    output_dir.mkdir(parents=True, exist_ok=True)

    resolved_latexmk = config.build.use_latexmk if use_latexmk is None else use_latexmk
    if resolved_latexmk and find_executable(LATEXMK_PROGRAM) is None:
        _LOG.warning("latexmk is not installed; falling back to the manual pass sequence")
        resolved_latexmk = False

    results = _run_sequence(config, source, output_dir, use_latexmk=resolved_latexmk, target=target)

    spec = engine_spec(config.build.engine)
    job = source.stem
    intermediate = output_dir / f"{job}{spec.intermediate_suffix}"
    produced: Path | None = None

    if spec.needs_dvipdfmx and intermediate.is_file():
        require_executable("dvipdfmx", purpose="converting the DVI to PDF")
        pdf = output_dir / f"{job}.pdf"
        results.append(
            run_command(
                dvipdfmx_command(intermediate, pdf, landscape=target is BuildTarget.SPINE),
                cwd=output_dir,
                env=build_environment(config),
            )
        )
        produced = pdf if pdf.is_file() else None
    else:
        candidate = output_dir / f"{job}.pdf"
        produced = candidate if candidate.is_file() else None

    log = parse_log(output_dir / f"{job}.log")
    missing_fonts = parse_missfont(output_dir / "missfont.log") or parse_missfont(
        config.root / "missfont.log"
    )

    for message in log.messages[:_MAX_REPORTED_MESSAGES]:
        severity = {
            "error": Severity.ERROR,
            "warning": Severity.WARNING,
            "info": Severity.INFO,
        }[message.severity.value]
        findings.append(
            Finding(
                severity=severity,
                kind=message.kind.value,
                location=message.location(),
                message=message.message,
            )
        )
    if len(log.messages) > _MAX_REPORTED_MESSAGES:
        findings.append(
            Finding(
                severity=Severity.INFO,
                kind="log-truncated",
                location=str(output_dir / f"{job}.log"),
                message=(
                    f"{len(log.messages) - _MAX_REPORTED_MESSAGES} further log message(s) "
                    "were omitted; see the .log file."
                ),
            )
        )

    for font in missing_fonts:
        findings.append(
            Finding(
                severity=Severity.WARNING,
                kind="missing-font",
                location="missfont.log",
                message=f"A font had to be generated or was substituted: {font}",
                detail="Output is silently degraded; run 'thesis-cli deps' to check the fonts.",
            )
        )

    failed = [result for result in results if not _succeeded(result)]
    command_rows = tuple(
        (
            result.command[0],
            " ".join(result.command[1:])[:80],
            str(result.returncode),
            f"{result.duration:.1f}s",
        )
        for result in results
    )
    tables = [
        ReportTable(
            title="Commands",
            columns=("program", "arguments", "exit", "time"),
            rows=command_rows,
        )
    ]
    counts = log.counts()
    if counts:
        tables.append(
            ReportTable(
                title="Log message summary",
                columns=("kind", "count"),
                rows=tuple((kind, str(count)) for kind, count in counts.items()),
            )
        )

    worst = log.worst_overfull
    summary = {
        "target": target.value,
        "source": str(source),
        "engine": config.build.engine.value,
        "driver": LATEXMK_PROGRAM if resolved_latexmk else "manual passes",
        "output": str(produced) if produced else "none",
        "passes": len(results),
        "log_errors": len(log.errors),
        "log_warnings": len(log.warnings),
        "worst_overfull_pt": worst.amount if worst else 0.0,
        "rerun_requested": log.rerun_needed,
    }

    report = CommandReport(
        command=f"build ({target.value})",
        findings=tuple(findings),
        tables=tuple(tables),
        summary=summary,
    )

    if failed or produced is None:
        reason = (
            f"{failed[0].command[0]} exited with status {failed[0].returncode}"
            if failed
            else "no PDF was produced"
        )
        raise BuildFailedError(
            f"Build failed: {reason}.",
            hint=f"See {output_dir / (job + '.log')} for the full engine output.",
            report=report,
        )

    _LOG.info("Built %s in %d command(s)", produced, len(results))
    return report


def attached_report(error: BaseException) -> CommandReport | None:
    """Recover the partial report attached to a failed build, if any.

    Parameters
    ----------
    error : BaseException
        The exception caught by the CLI.

    Returns
    -------
    CommandReport or None
        The partial report, or ``None`` when the error carries none.
    """
    report = getattr(error, "report", None)
    return report if isinstance(report, CommandReport) else None
