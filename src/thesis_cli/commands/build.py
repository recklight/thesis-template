r"""The ``build`` command: compile the thesis with one command.

By hand, a thesis build is several commands in a fixed order, and two
mistakes are easy to make: running the engine one pass too few, which
leaves ``??`` where the cross-references should be, and pointing it at a
file with no preamble, which answers with a screen of ``Undefined control
sequence`` that says nothing about the real mistake.

``latexmk`` decides the number of passes; it reruns until the ``.aux``
stops changing.  Where ``latexmk`` is not installed, a fixed sequence runs
instead: one engine pass, ``bibtex`` if that pass wrote a ``\bibdata``, then
the remaining engine passes up to ``build.max_passes``.  Before any program
starts, a target without a preamble is refused, and a preflight pass
reports missing graphics, bibliography files and watermark, each with a
message that says what to fix, instead of letting TeX fail later with
something unrelated.
"""

